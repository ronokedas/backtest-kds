"""Gemini AI Gatekeeper & Institutional Signal Auditor.

Evaluates high-probability trade setups generated by the quantitative engines,
acting as a secondary risk filter to eliminate false breakouts, low-volume traps,
and adverse structural positioning.
"""

import os
import json
import logging
from typing import Dict, Any, Optional
import urllib.request
import urllib.error

logger = logging.getLogger(__name__)


class GeminiAIAuditor:
    """Audits quantitative trade signals using Gemini API or high-precision deterministic fallback."""

    def __init__(
        self,
        api_key: Optional[str] = None,
        model: str = "gemini-2.5-flash",
        min_confidence: float = 70.0,
        enabled: bool = True,
    ):
        self.api_key = api_key or os.getenv("GEMINI_API_KEY")
        self.model = model
        self.min_confidence = min_confidence
        self.enabled = enabled

    def build_trade_dossier(
        self,
        symbol: str,
        signal: Any,  # EngineSignal
        struct_data: Dict[str, Any],
        fib_data: Dict[str, Any],
        vp_data: Dict[str, Any],
        oi_data: Dict[str, Any],
        funding_rate: Optional[float] = None,
    ) -> Dict[str, Any]:
        """Builds a high-density structured JSON snapshot of the trade setup."""
        price = float(signal.price)
        inv = float(signal.invalidation) if signal.invalidation else price * 0.99
        t1 = float(signal.target_1) if signal.target_1 else price * 1.02
        t2 = float(signal.target_2) if signal.target_2 else price * 1.04

        risk = abs(price - inv)
        reward_1 = abs(t1 - price)
        rr_ratio = (reward_1 / risk) if risk > 0 else 0.0

        return {
            "symbol": symbol,
            "engine": signal.engine_name,
            "side": signal.side,
            "score": signal.score,
            "state": signal.state,
            "execution": {
                "entry_price": round(price, 4),
                "invalidation_stop": round(inv, 4),
                "target_1": round(t1, 4),
                "target_2": round(t2, 4),
                "risk_reward_1": round(rr_ratio, 2),
            },
            "market_structure": {
                "choch_bullish": struct_data.get("choch_bullish", False),
                "choch_bearish": struct_data.get("choch_bearish", False),
                "bos_bullish": struct_data.get("bos_bullish", False),
                "bos_bearish": struct_data.get("bos_bearish", False),
                "is_retest": struct_data.get("is_choch_retest", False) or struct_data.get("is_bos_retest", False),
            },
            "fibonacci": {
                "in_golden_zone": fib_data.get("in_golden_zone", False),
                "fib_50": fib_data.get("fib_50", 0.0),
                "fib_618": fib_data.get("fib_618", 0.0),
                "distance_pct": fib_data.get("distance_to_golden_zone_pct", 0.0),
            },
            "volume_profile": {
                "poc": vp_data.get("poc", 0.0),
                "vah": vp_data.get("vah", 0.0),
                "val": vp_data.get("val", 0.0),
                "val_sweep_bullish": vp_data.get("val_sweep_bullish", False),
                "vah_sweep_bearish": vp_data.get("vah_sweep_bearish", False),
                "distance_to_poc_pct": vp_data.get("distance_to_poc_pct", 0.0),
            },
            "order_flow_and_oi": {
                "retest_cvd_divergence": signal.metrics.get("retest_cvd_div", False),
                "delta_zscore": signal.metrics.get("delta_z", 0.0),
                "rvol": signal.metrics.get("rvol", 1.0),
                "short_trap_bullish": oi_data.get("short_trap_bullish", False),
                "long_trap_bearish": oi_data.get("long_trap_bearish", False),
                "oi_change_15m_pct": oi_data.get("oi_change_15m_pct", 0.0),
                "funding_rate": funding_rate,
            },
            "tactical_trigger_m5": {
                "m5_engulfing": signal.metrics.get("m5_engulfing", False),
                "m5_delta": signal.metrics.get("m5_delta", 0.0),
                "volatility_squeeze": signal.metrics.get("is_squeezed", False),
                "orderbook_imbalance": signal.metrics.get("obi", 0.0),
            },
            "reasons": signal.reasons,
        }

    def audit_trade(self, dossier: Dict[str, Any]) -> Dict[str, Any]:
        """Audits the trade setup via Gemini LLM or robust deterministic fallback."""
        if not self.enabled:
            return {
                "authorized": True,
                "confidence": 100.0,
                "rationale": "Auditoria de IA desativada por configuração (aprovação automática).",
                "risk_rating": "LOW",
                "source": "CONFIG_BYPASS",
            }

        if self.api_key:
            try:
                return self._call_gemini_api(dossier)
            except Exception as e:
                logger.warning(f"Falha na chamada Gemini API ({e}). Utilizando fallback determinístico quantitativo.")

        # Quantitative Deterministic Fallback Auditor
        return self._deterministic_audit(dossier)

    def _call_gemini_api(self, dossier: Dict[str, Any]) -> Dict[str, Any]:
        """Calls Google Gemini REST API to evaluate the trade snapshot."""
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model}:generateContent?key={self.api_key}"

        system_instruction = (
            "Você é o Diretor Sênior de Risco e Confluência Quantitativa de um Hedge Fund Institucional especializado em Binance Futures. "
            "Sua missão é auditar um dossiê técnico de trade SMC (Smart Money Concepts), Volume Profile, CVD e Open Interest. "
            "Responda EXCLUSIVAMENTE em formato JSON com o seguinte esquema:\n"
            "{\n"
            '  "decision": "AUTHORIZED" ou "REJECTED",\n'
            '  "confidence": número de 0 a 100,\n'
            '  "risk_rating": "LOW" ou "MEDIUM" ou "HIGH",\n'
            '  "rationale": "Parecer sucinto em 1 a 2 frases explicando por que autorizou ou rejeitou."\n'
            "}\n"
            "Diretrizes de Risco:\n"
            "- AUTORIZE se houver confluência entre reteste de Fibonacci/Suporte e evidência de absorção no CVD/Volume Profile/OI Trap, com Risco/Retorno >= 2.0.\n"
            "- REJEITE se o preço estiver esticado longe do stop, se o R:R for desfavorável (< 1.5), ou se não houver confirmação de absorção."
        )

        prompt_body = {
            "contents": [
                {
                    "parts": [
                        {"text": f"{system_instruction}\n\nDossiê do Trade para Avaliação:\n{json.dumps(dossier, indent=2, ensure_ascii=False)}"}
                    ]
                }
            ],
            "generationConfig": {
                "temperature": 0.1,
                "responseMimeType": "application/json",
            },
        }

        req = urllib.request.Request(
            url,
            data=json.dumps(prompt_body).encode("utf-8"),
            headers={"Content-Type": "application/json"},
            method="POST",
        )

        with urllib.request.urlopen(req, timeout=8.0) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            content_text = data["candidates"][0]["content"]["parts"][0]["text"]
            res = json.loads(content_text)

            decision = str(res.get("decision", "REJECTED")).upper()
            confidence = float(res.get("confidence", 50.0))
            is_authorized = (decision == "AUTHORIZED") and (confidence >= self.min_confidence)

            return {
                "authorized": is_authorized,
                "confidence": confidence,
                "risk_rating": res.get("risk_rating", "MEDIUM"),
                "rationale": res.get("rationale", "Avaliado via Gemini AI."),
                "source": f"GEMINI_{self.model.upper()}",
            }

    def _deterministic_audit(self, dossier: Dict[str, Any]) -> Dict[str, Any]:
        """Quantitative rules when offline or API key is not configured."""
        score = float(dossier.get("score", 0.0))
        exec_info = dossier.get("execution", {})
        rr = float(exec_info.get("risk_reward_1", 0.0))

        of = dossier.get("order_flow_and_oi", {})
        vp = dossier.get("volume_profile", {})
        tactical = dossier.get("tactical_trigger_m5", {})
        struct = dossier.get("market_structure", {})

        has_retest_cvd = of.get("retest_cvd_divergence", False)
        has_trap = of.get("short_trap_bullish", False) or of.get("long_trap_bearish", False)
        has_vp_sweep = vp.get("val_sweep_bullish", False) or vp.get("vah_sweep_bearish", False)
        has_m5 = tactical.get("m5_engulfing", False)
        is_retest = struct.get("is_retest", False)

        rejection_reasons = []

        if rr < 1.5:
            rejection_reasons.append(f"Risco/Retorno insuficiente ({rr:.2f} < 1.5)")

        if score < 70.0:
            rejection_reasons.append(f"Score de confluência inferior a 70.0 ({score:.1f})")

        key_confirmations = sum([has_retest_cvd, has_trap, has_vp_sweep, has_m5, is_retest])

        if rejection_reasons:
            return {
                "authorized": False,
                "confidence": 40.0,
                "risk_rating": "HIGH",
                "rationale": f"Rejeitado pela Auditoria Quantitativa: {'; '.join(rejection_reasons)}.",
                "source": "QUANT_GATEKEEPER_DETERMINISTIC",
            }

        # Calculation of institutional confidence
        base_confidence = min(98.0, 60.0 + (key_confirmations * 7.0) + (rr * 3.0))

        return {
            "authorized": True,
            "confidence": round(base_confidence, 1),
            "risk_rating": "LOW" if key_confirmations >= 3 else "MEDIUM",
            "rationale": f"Trade Aprovado com {key_confirmations} confluências institucionais ativas e R:R {rr:.2f}.",
            "source": "QUANT_GATEKEEPER_DETERMINISTIC",
        }

